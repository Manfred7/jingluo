export interface Point {
  /** 'LI-4' */
  id: string;
  channel: ChannelId;
  number: number;
  /** Код по Мачоча: 'L.I.-4' */
  code: string;
  /** Код ВОЗ: 'LI4' */
  who: string;
  nameRu: string;
  hanzi: string;
  bilateral: boolean;
}

function parse(channel: ChannelId, raw: string): Point[] {
  const ch = channelById(channel);
  return raw.split(' · ').map((item) => {
    const m = /^(\d+) (\S+) (\S+)$/.exec(item.trim());
    if (!m) throw new Error(`Не разобрана точка «${item}» канала ${channel}`);
    const number = Number(m[1]);
    return {
      id: `${channel}-${number}`,
      channel,
      number,
      code: `${ch.code}-${number}`,
      who: `${ch.who}${number}`,
      nameRu: m[2],
      hanzi: m[3],
      bilateral: ch.bilateral,
    };
  });
}

export const POINTS: Point[] = CHANNELS.flatMap((c) => parse(c.id, RAW[c.id]));

export const pointsOf = (channel: ChannelId) => POINTS.filter((p) => p.channel === channel);
export const pointById = (id: string) => POINTS.find((p) => p.id === id);
