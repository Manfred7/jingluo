/**
 * Голень по линии ST-35 — ST-41: n цуней ниже ST-35, на палец кнаружи от гребня большеберцовой кости.
 * Гребень на этом виде — передний контур, «кнаружи» — назад (влево); d — ещё на сколько цуней кнаружи.
 */
const shin = (n: number, d = 0): Vec => across(along(st35, st41, n, 16), st35, st41, 12 + d * CUN);
