const mal = L.malleolus;
/** Вверх от лодыжки по малоберцовой кости: n цуней выше верхушки лодыжки, сдвиг вперёд dx */
const aboveMal = (n: number, dx = 0): Vec => [mal[0] + 4 + dx, mal[1] - n * CUN];

